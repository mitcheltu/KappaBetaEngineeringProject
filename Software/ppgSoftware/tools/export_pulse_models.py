"""Export notebook 04's frozen artifacts to allocation-free C++ parameters.

Run only on trusted local joblib/PT files (joblib deserialization executes code).
No training, threshold selection or network access occurs here.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import joblib
import numpy as np
from scipy import signal

FEATURES = ["max_gap_s", "tail_gap_s", "n_beats", "hr_median", "hr_min5",
            "ibi_cv", "amp_tail_ratio", "spectral_purity", "flat_fraction", "kurtosis"]


def number(value, single=False):
    value = float(value)
    if not np.isfinite(value):
        raise ValueError("Parameters must be finite")
    result = format(value, ".9g" if single else ".17g")
    if "." not in result and "e" not in result:
        result += ".0"
    return result + ("f" if single else "")


def array(name, values, single=False):
    values = np.asarray(values).ravel()
    rows = [", ".join(number(v, single) for v in values[i:i + 6])
            for i in range(0, len(values), 6)]
    return (f"constexpr {'float' if single else 'double'} {name}[{len(values)}] = {{\n  "
            + ",\n  ".join(rows) + "\n};\n")


def export(source: Path, output: Path):
    config_path = source / "pulse_loss_configuration.json"
    model_path = source / "pulse_loss_feature_models.joblib"
    cnn_path = source / "pulse_loss_cnn_1d.pt"
    config = json.loads(config_path.read_text(encoding="utf-8"))
    expected_input = {"rate_hz": 100, "window_s": 16, "band_hz": [0.5, 8.0],
                      "scaling": "5-95 percentile spread"}
    if config["input"] != expected_input or config["features"] != FEATURES:
        raise ValueError("This export supports only notebook 04's 100 Hz / 16 s / ten-feature pipeline")
    if config.get("deployable") is not False:
        raise ValueError("Preserve the research-only deployable:false provenance")
    models = joblib.load(model_path)
    logistic = models["logistic"]
    scaler, clf = logistic.named_steps["standardscaler"], logistic.named_steps["logisticregression"]
    if list(clf.classes_) != [0, 1] or clf.coef_.shape != (1, 10):
        raise ValueError("Unexpected logistic classifier")
    boosted = models["boosted_trees"]
    if list(boosted.classes_) != [0, 1]:
        raise ValueError("Expected a binary tree ensemble")
    sos = signal.butter(3, [0.5, 8.0], fs=100, btype="band", output="sos")
    zi = signal.sosfilt_zi(sos)
    parts = ["// Generated by tools/export_pulse_models.py; do not edit weights by hand.\n"
             "// Notebook 04 research artifacts: deployable=false; see pulse_model_manifest.json.\n"
             "#pragma once\n#include <cstddef>\n#include <cstdint>\n"
             "namespace Ppg { namespace PulseParams {\n"
             "constexpr bool HasLogistic = true, HasBoostedTrees = true;\n",
             array("Sos", sos), array("Zi", zi), array("LogMean", scaler.mean_),
             array("LogScale", scaler.scale_), array("LogCoefficient", clf.coef_),
             f"constexpr double LogIntercept = {number(clf.intercept_[0])};\n",
             "struct TreeNode { double value, threshold; uint16_t left, right; uint8_t feature; bool leaf, missingLeft; };\n"]
    nodes, offsets = [], []
    for iteration in boosted._predictors:
        if len(iteration) != 1:
            raise ValueError("Expected one tree per binary boosting iteration")
        offsets.append(len(nodes))
        for node in iteration[0].nodes:
            if node["is_categorical"]:
                raise ValueError("Categorical splits are not supported")
            nodes.append("{" + ", ".join([
                number(node["value"]), number(node["num_threshold"]), str(int(node["left"])),
                str(int(node["right"])), str(int(node["feature_idx"])),
                str(bool(node["is_leaf"])).lower(), str(bool(node["missing_go_to_left"])).lower()]) + "}")
    if len(nodes) >= 65536:
        raise ValueError("Ensemble does not fit uint16 node offsets")
    parts += [f"constexpr double TreeBaseline = {number(boosted._baseline_prediction.item())};\n",
              f"constexpr std::size_t TreeCount = {len(offsets)};\n",
              "constexpr uint16_t TreeOffsets[] = {" + ", ".join(map(str, offsets)) + "};\n",
              "constexpr TreeNode TreeNodes[] = {\n  " + ",\n  ".join(nodes) + "\n};\n"]
    if cnn_path.exists():
        import torch
        state = torch.load(cnn_path, map_location="cpu", weights_only=True)
        specs = [("body.0.weight", "Conv1Weight", (8, 1, 7)), ("body.0.bias", "Conv1Bias", (8,)),
                 ("body.3.weight", "Conv2Weight", (16, 8, 7)), ("body.3.bias", "Conv2Bias", (16,)),
                 ("body.6.weight", "Conv3Weight", (32, 16, 5)), ("body.6.bias", "Conv3Bias", (32,)),
                 ("head.weight", "HeadWeight", (1, 32)), ("head.bias", "HeadBias", (1,))]
        if set(state) != {key for key, _, _ in specs}:
            raise ValueError("Unexpected CNN state keys")
        parts += ["constexpr bool HasCnn = true;\n"]
        for key, name, shape in specs:
            if tuple(state[key].shape) != shape:
                raise ValueError(f"Unexpected tensor shape for {key}")
            parts.append(array(name, state[key].numpy(), single=True))
    else:
        # The inference header compiles with missing CNN artifacts, but never presents a fake score.
        parts += ["constexpr bool HasCnn = false;\n"]
        for name, size in [("Conv1Weight", 56), ("Conv1Bias", 8), ("Conv2Weight", 896),
                           ("Conv2Bias", 16), ("Conv3Weight", 2560), ("Conv3Bias", 32),
                           ("HeadWeight", 32), ("HeadBias", 1)]:
            parts.append(f"constexpr float {name}[{size}] = {{}}; // unavailable, never evaluated\n")
    points = ["high_sensitivity", "high_specificity"]
    thresholds = [0.5, 0.5]
    for model in ["logistic", "boosted_trees", "cnn_1d"]:
        values = config["final_thresholds"].get(model, {p: 1.0 for p in points})
        thresholds += [values[p] for p in points]
    parts += [array("Thresholds", thresholds), "} } // namespace Ppg::PulseParams\n"]
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("".join(parts), encoding="utf-8", newline="\n")
    sources = [config_path, model_path] + ([cnn_path] if cnn_path.exists() else [])
    notebook = Path(__file__).resolve().parents[2] / "GoogleColab" / "04_pulse_loss_detector.ipynb"
    manifest = {"deployable": False, "source_configuration": config,
                "notebook_sha256": hashlib.sha256(notebook.read_bytes()).hexdigest(),
                "source_sha256": {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in sources},
                "header_sha256": hashlib.sha256(output.read_bytes()).hexdigest(),
                "tree_count": len(offsets), "tree_nodes": len(nodes), "cnn_present": cnn_path.exists(),
                "feature_order": FEATURES, "filter": "scipy.signal.butter(3,[0.5,8],fs=100,output='sos')"}
    output.with_name("pulse_model_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"Exported {len(nodes)} nodes in {len(offsets)} trees to {output}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="Directory of trusted notebook 04 artifacts")
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "PulseLossParams.h")
    args = parser.parse_args()
    export(args.source, args.output)
