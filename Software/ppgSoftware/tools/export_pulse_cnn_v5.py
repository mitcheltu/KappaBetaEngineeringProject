"""Export notebook 04 v5's `cnn_v5_h` ensemble to C++ and write PyTorch parity fixtures.

Run only on trusted local notebook outputs. Loading uses torch.load(weights_only=True),
so it does not unpickle arbitrary objects. Nothing here trains, tunes thresholds, or
downloads data. The model architecture is extracted from the checked-in notebook source,
so the exported layer specification cannot drift from the code that trained it.

    python Software/ppgSoftware/tools/export_pulse_cnn_v5.py tmp/kaggle-qa/v6/out04_full
"""
from __future__ import annotations

import argparse
import ast
import csv
import hashlib
import json
from pathlib import Path

import numpy as np

from export_pulse_models import array, number
from generate_pulse_golden import reference

MODEL = "cnn_v5_h"
# (state key prefix, C++ name, shape) in forward order; must match PulseCnnV5.h.
LAYERS = [("body.0", "Conv1", (8, 1, 9)), ("body.3", "Conv2", (16, 8, 7)),
          ("body.6", "Conv3", (16, 16, 7)), ("body.9", "Conv4", (24, 16, 5)),
          ("body.12", "Conv5", (24, 24, 5)), ("head.2", "Head", (1, 192))]
EXPECTED_INPUT = {"rate_hz": 100, "window_s": 16, "band_hz": [0.5, 8.0],
                  "scaling": "5-95 percentile spread",
                  "ir_sign": "clinical PLETH convention (raw optical intensity negated)"}


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load_network_class(notebook: Path):
    cells = json.loads(notebook.read_text(encoding="utf-8"))["cells"]
    source = next("".join(c["source"]) for c in cells
                  if c["cell_type"] == "code" and "class PulseCNN5(" in "".join(c["source"]))
    node = next(n for n in ast.walk(ast.parse(source))
                if isinstance(n, ast.ClassDef) and n.name == "PulseCNN5")
    from torch import nn
    namespace = {"nn": nn}
    exec(compile(ast.Module(body=[node], type_ignores=[]), str(notebook), "exec"), namespace)
    return namespace["PulseCNN5"]


def export(source: Path, header: Path, fixtures: Path, notebook: Path):
    import torch
    torch.set_num_threads(1)
    config_path, weights_path = source / "pulse_loss_configuration.json", source / f"pulse_loss_{MODEL}.pt"
    config = json.loads(config_path.read_text(encoding="utf-8"))
    if config.get("deployable") is not False or config.get("quick_smoke_test") is not False:
        raise ValueError("Export only a full (non-smoke) research run that keeps deployable:false")
    if config["input"] != EXPECTED_INPUT:
        raise ValueError(f"Unsupported input contract: {config['input']}")
    thresholds = config["final_thresholds"][MODEL]
    plan = json.loads((source / "v5_run_plan.json").read_text(encoding="utf-8"))
    if plan.get("quick") is not False:
        raise ValueError("Smoke-test run plans cannot be exported")
    saved = torch.load(weights_path, map_location="cpu", weights_only=True)
    members = saved["state_dicts"]
    if len(members) != 3:
        raise ValueError("Expected the 3-seed ensemble")
    expected_keys = {f"{p}.{t}" for p, _, _ in LAYERS for t in ("weight", "bias")}
    for state in members:
        if set(state) != expected_keys:
            raise ValueError(f"Unexpected state keys: {sorted(state)}")
        for prefix, _, shape in LAYERS:
            if tuple(state[prefix + ".weight"].shape) != shape:
                raise ValueError(f"Unexpected shape for {prefix}")

    # Parameter header: [member][out][in][tap] weights, [member][out] biases.
    parts = ["// Generated by tools/export_pulse_cnn_v5.py; do not edit weights by hand.\n"
             "// Notebook 04 v5 cnn_v5_h research artifact: deployable=false; see pulse_cnn_v5_manifest.json.\n"
             "#pragma once\n#include <cstddef>\n"
             "namespace Ppg { namespace PulseCnnV5Params {\n"
             "constexpr bool Available = true;\n"
             f"constexpr std::size_t Members = {len(members)};\n",
             "// Inner-CV operating points chosen in the final fit: [high_sensitivity, high_specificity].\n",
             array("Thresholds", [thresholds["high_sensitivity"], thresholds["high_specificity"]])]
    for prefix, name, _ in LAYERS:
        for kind in ("weight", "bias"):
            values = np.concatenate([m[f"{prefix}.{kind}"].numpy().ravel() for m in members])
            parts.append(array(f"{name}{kind.capitalize()}", values, single=True))
    parts.append("} } // namespace Ppg::PulseCnnV5Params\n")
    header.write_text("".join(parts), encoding="utf-8", newline="\n")

    # Parity fixtures: the existing synthetic raw waveforms, PyTorch float32 forward pass.
    ns, _ = reference(notebook)
    Net = load_network_class(notebook)
    nets = []
    for state in members:
        net = Net()
        net.load_state_dict(state)
        net.eval()
        nets.append(net)
    raw = {}
    with (fixtures / "pulse_waveforms.csv").open(encoding="utf-8") as stream:
        for row in csv.DictReader(stream):
            raw.setdefault(row["case"], []).append(float(np.float32(row["raw"])))
    rows = []
    for name, values in raw.items():
        prepared = torch.tensor(ns["prepare"](np.asarray(values, float))[None, :], dtype=torch.float32)
        with torch.no_grad():
            member = [float(torch.sigmoid(net(prepared))[0]) for net in nets]
        score = float(np.mean(member))
        rows.append([name] + [format(v, ".9g") for v in member] + [format(score, ".9g"),
                     int(score >= thresholds["high_sensitivity"]), int(score >= thresholds["high_specificity"])])
    expected = fixtures / "pulse_cnn_v5_expected.csv"
    with expected.open("w", encoding="utf-8", newline="") as out:
        writer = csv.writer(out, lineterminator="\n")
        writer.writerow(["case", "member0", "member1", "member2", "score", "high_sensitivity", "high_specificity"])
        writer.writerows(rows)

    with (source / "cv_results.csv").open(encoding="utf-8") as stream:
        cv = next(r for r in csv.DictReader(stream)
                  if r["model"] == MODEL and r["operating_point"] == "high_specificity")
    cv = {k: float(v) for k, v in cv.items() if k not in ("model", "operating_point")}
    selection = json.loads((source / "firmware_selection.json").read_text(encoding="utf-8"))
    candidate = next(c for c in selection["candidates"] if c["model"] == MODEL)
    manifest = {
        "model": MODEL, "deployable": False, "drowning_detector": False,
        "status": ("post-hoc research choice for on-device display: notebook 04 v5's predeclared rule selected "
                   "cnn_1d; cnn_v5_h had higher ICU sensitivity at a higher healthy false-alert rate"),
        "architecture": "PulseCNN5: Conv(1>8,k9,s2)+pool2, Conv(8>16,k7)+pool2, Conv(16>16,k7)+pool2, "
                        "Conv(16>24,k5,d2)+pool2, Conv(24>24,k5,d2)+adaptive-max(8), Linear(192>1); ReLU; "
                        "mean of 3 member sigmoids",
        "training": "PhysioNet/CinC 2015 ICU alarms (514 records, 123 true) plus 50 pulse-visible healthy "
                    "WildPPG sternum windows from each of " + ", ".join(plan["wildppg_train"]),
        "best_epochs": saved["best_epochs"],
        "input": config["input"], "thresholds": thresholds,
        "outer_cv_high_specificity": {k: cv[k] for k in ("AUROC", "sensitivity", "specificity", "TP", "FN", "TN", "FP")},
        "healthy_gated_false_alert_starts_per_monitored_hour": candidate["per_hour"],
        "evidence_files": ["cv_results.csv", "firmware_selection.json"],
        "parameters_per_member": int(sum(v.numel() for v in members[0].values())),
        "notebook_sha256": sha256(notebook),
        "source_sha256": {p.name: sha256(p) for p in (config_path, weights_path)},
        "header_sha256": sha256(header), "fixture_sha256": {expected.name: sha256(expected)},
        "parity_tolerance": "absolute 2e-5 on probabilities (float32 accumulation order differs)",
    }
    header.with_name("pulse_cnn_v5_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"Exported {MODEL}: {len(members)} members x {manifest['parameters_per_member']} parameters; "
          f"{len(rows)} parity cases")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="Directory of trusted notebook 04 v5 outputs")
    root = Path(__file__).resolve().parents[2]
    parser.add_argument("--header", type=Path, default=root / "ppgSoftware" / "PulseCnnV5Params.h")
    parser.add_argument("--fixtures", type=Path, default=root / "tests" / "ppg")
    parser.add_argument("--notebook", type=Path, default=root / "GoogleColab" / "04_pulse_loss_detector.ipynb")
    args = parser.parse_args()
    export(args.source, args.header, args.fixtures, args.notebook)
