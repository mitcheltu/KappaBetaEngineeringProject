// Generates Software/tests/scenario-protocol-fixture.json from the firmware's real scenario
// wire types (ScenarioProtocol.h) and compiled catalog (ScenarioData.h). The web app's
// scenarioProtocol tests decode these exact bytes. Regenerate after any protocol change:
//   g++ -std=c++17 -O2 -I Software/testsAndDemo/DrowningWearableDemo Software/tests/scenario_fixture.cpp -o tmp/scenario_fixture.exe
//   ./tmp/scenario_fixture.exe > Software/tests/scenario-protocol-fixture.json
#include "ScenarioData.h"
#include <cstdio>
#include <cstring>
#include <vector>

using namespace Scenario;

static void hex(const void* data, size_t n) {
  const auto* b = static_cast<const uint8_t*>(data);
  std::printf("\"");
  for (size_t i = 0; i < n; ++i) std::printf("%02x", b[i]);
  std::printf("\"");
}

int main() {
  CompiledSource source;
  // Catalog bytes, packed exactly like Scenario.ino's scenarioCatalog().
  CatalogHeader header;
  header.count = static_cast<uint8_t>(source.count());
  header.catalogCrc = catalogCrc(source);
  std::vector<uint8_t> catalog(sizeof(header) + source.count() * sizeof(CatalogEntry));
  std::memcpy(catalog.data(), &header, sizeof(header));
  for (size_t i = 0; i < source.count(); ++i) {
    CatalogEntry entry;
    source.descriptor(i, entry.descriptor);
    std::strncpy(entry.name, source.name(i), NAME_BYTES - 1);
    std::memcpy(catalog.data() + sizeof(header) + i * sizeof(entry), &entry, sizeof(entry));
  }
  std::printf("{\n  \"note\": \"Generated by Software/tests/scenario_fixture.cpp from the firmware wire types.\",\n");
  std::printf("  \"catalog\": {\"hex\": ");
  hex(catalog.data(), catalog.size());
  std::printf(", \"crc\": %u, \"entries\": [", header.catalogCrc);
  for (size_t i = 0; i < source.count(); ++i) {
    Descriptor d;
    source.descriptor(i, d);
    std::printf("%s\n    {\"id\": %u, \"name\": \"%s\", \"irSamples\": %u, \"imuSamples\": %u, \"spo2Samples\": %u, \"contentCrc32\": %u}",
                i ? "," : "", d.id, source.name(i), d.irSamples, d.imuSamples, d.spo2Samples, d.contentCrc32);
  }
  std::printf("]},\n");
  Command start{};
  start.opcode = static_cast<uint8_t>(Opcode::START);
  start.token = 0x1234;
  start.scenarioId = 2;
  start.catalogCrc = header.catalogCrc;
  Command abortCommand{};
  abortCommand.opcode = static_cast<uint8_t>(Opcode::ABORT);
  abortCommand.token = 0x0042;
  std::printf("  \"commands\": {\"start\": {\"token\": 4660, \"scenarioId\": 2, \"hex\": ");
  hex(&start, sizeof(start));
  std::printf("}, \"abort\": {\"token\": 66, \"hex\": ");
  hex(&abortCommand, sizeof(abortCommand));
  std::printf("}},\n  \"statuses\": [");
  Status s{};
  s.state = static_cast<uint8_t>(State::ACTUATING);
  s.commandToken = 0x1234;
  s.scenarioId = 2;
  s.flags = PULSE_ALERT | TRIGGER_ACCEPTED | PULSE_VALID | CONCERN_VALID | SCENARIOS_COMPILED | IMU_GATE_OPEN;
  s.remainingMs = 21980;
  s.catalogCrc = header.catalogCrc;
  s.pulseScore = scaleUnit(0.9622f);
  s.oxygenConcern = scaleUnit(0.0f);
  s.runToken = 0x1234;
  std::printf("\n    {\"state\": \"actuating\", \"reason\": 0, \"scenarioId\": 2, \"remainingMs\": 21980, \"pulseScore\": %u, \"oxygenConcern\": %u, \"pulseAlert\": true, \"oxygenAlert\": false, \"imuGateOpen\": true, \"triggerAccepted\": true, \"hex\": ",
              s.pulseScore, s.oxygenConcern);
  hex(&s, sizeof(s));
  std::printf("},");
  Status r{};
  r.state = static_cast<uint8_t>(State::REJECTED);
  r.reason = static_cast<uint8_t>(Reason::BATTERY_NOT_READY);
  r.commandToken = 7;
  r.scenarioId = 9;
  r.flags = SCENARIOS_COMPILED;
  r.catalogCrc = header.catalogCrc;
  std::printf("\n    {\"state\": \"rejected\", \"reason\": 1, \"scenarioId\": 9, \"remainingMs\": 0, \"pulseScore\": null, \"oxygenConcern\": null, \"pulseAlert\": false, \"oxygenAlert\": false, \"imuGateOpen\": false, \"triggerAccepted\": false, \"hex\": ");
  hex(&r, sizeof(r));
  std::printf("}\n  ]\n}\n");
}
