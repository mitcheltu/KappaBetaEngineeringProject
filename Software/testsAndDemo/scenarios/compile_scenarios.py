"""Compile the scenario CSVs into DrowningWearableDemo/ScenarioData.h (const flash data).

Needs only the CSVs and scenarios.json, not the datasets, so an edited CSV can be recompiled
directly. CSV contract (100 Hz rows, t_ms = 10 * row):
  ir            every row, finite (PLETH convention)
  ax..gz        every 5th row (t_ms % 50 == 0): m/s^2 and rad/s; blank otherwise
  spo2, spo2_valid  every 100th row (t_ms % 1000 == 0); spo2 blank when spo2_valid = 0

    python Software/testsAndDemo/scenarios/compile_scenarios.py
"""
from __future__ import annotations

import json
import struct
import zlib
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
HEADER = HERE.parent / "DrowningWearableDemo" / "ScenarioData.h"
NAME_BYTES = 24


def literal(v):
    text = format(float(v), ".7g")
    return text + ("f" if any(c in text for c in ".en") else ".0f")


def floats(name, values, per_line=10):
    values = np.asarray(values, np.float32)
    rows = [",".join(literal(v) for v in values[i:i + per_line])
            for i in range(0, len(values), per_line)]
    return f"constexpr float {name}[{len(values)}] = {{\n" + ",\n".join(rows) + "\n};\n"


def load(path: Path):
    d = pd.read_csv(path)
    if list(d.columns) != ["t_ms", "ir", "ax", "ay", "az", "gx", "gy", "gz", "spo2", "spo2_valid"]:
        raise ValueError(f"{path.name}: unexpected columns")
    if not (d.t_ms.to_numpy() == np.arange(len(d)) * 10).all():
        raise ValueError(f"{path.name}: t_ms must be 0,10,20,...")
    ir = d.ir.to_numpy(np.float32)
    imu_rows = d[d.t_ms % 50 == 0][["ax", "ay", "az", "gx", "gy", "gz"]].to_numpy(np.float32)
    spo2_rows = d[d.t_ms % 1000 == 0]
    valid = spo2_rows.spo2_valid.fillna(0).to_numpy(np.uint8)
    spo2 = np.where(valid == 1, spo2_rows.spo2.to_numpy(np.float32), 0).astype(np.float32)
    if not np.isfinite(ir).all() or not np.isfinite(imu_rows).all():
        raise ValueError(f"{path.name}: IR and IMU must be finite (use spo2_valid for SpO2 gaps)")
    if ((valid == 1) & ~((spo2 > 0) & (spo2 <= 100))).any():
        raise ValueError(f"{path.name}: valid SpO2 must be in (0, 100]")
    return ir, imu_rows, spo2, valid


def main():
    manifest = json.loads((HERE / "scenarios.json").read_text(encoding="utf-8"))
    parts = ["// Generated by Software/testsAndDemo/scenarios/compile_scenarios.py from the scenario CSVs.\n",
             "// Scripted demo playback only (see scenarios/README.md): not training, test or evidence data.\n",
             "#pragma once\n#include <stdint.h>\n#include <string.h>\n#include \"ScenarioSource.h\"\n\n",
             "namespace Scenario {\nnamespace Data {\n"]
    entries = []
    for sc in manifest["scenarios"]:
        ir, imu, spo2, valid = load(HERE / sc["csv"])
        if len(imu) > 65535:
            raise ValueError("imuSamples must fit uint16")
        crc = zlib.crc32(ir.astype("<f4").tobytes() + imu.astype("<f4").tobytes() +
                         spo2.astype("<f4").tobytes() + valid.tobytes()) & 0xffffffff
        name = sc["name"].encode("utf-8")[:NAME_BYTES - 1].decode("utf-8", "ignore")
        p = f"S{sc['id']}"
        parts += [f"// {sc['id']}: {sc['name']} -- {sc['story']}\n",
                  floats(f"{p}_IR", ir), floats(f"{p}_IMU", imu.ravel(), 6), floats(f"{p}_SPO2", spo2),
                  f"constexpr uint8_t {p}_SPO2_VALID[{len(valid)}] = {{" + ",".join(map(str, valid)) + "};\n\n"]
        entries.append(f"  {{{sc['id']}, \"{name}\", {p}_IR, {len(ir)}u, {p}_IMU, {len(imu)}u, "
                       f"{p}_SPO2, {p}_SPO2_VALID, {len(spo2)}u, 0x{crc:08x}u}}")
    parts += ["struct Entry {\n  uint8_t id;\n  const char* name;\n  const float* ir;\n  uint32_t irCount;\n",
              "  const float* imu;\n  uint16_t imuCount;\n  const float* spo2;\n  const uint8_t* spo2Valid;\n",
              "  uint32_t spo2Count;\n  uint32_t contentCrc32;\n};\n",
              f"constexpr Entry ENTRIES[{len(entries)}] = {{\n" + ",\n".join(entries) + "\n};\n",
              "}  // namespace Data\n\n",
              """// The compiled-in scenario catalog. Read-only flash data; select() is the only state.
class CompiledSource final : public Source {
 public:
  size_t count() const override { return sizeof(Data::ENTRIES) / sizeof(Data::ENTRIES[0]); }
  bool descriptor(size_t index, Descriptor& out) const override {
    if (index >= count()) return false;
    const Data::Entry& e = Data::ENTRIES[index];
    out = Descriptor{};
    out.id = e.id;
    out.version = 1;
    out.imuSamples = e.imuCount;
    out.irSamples = e.irCount;
    out.spo2Samples = e.spo2Count;
    out.contentCrc32 = e.contentCrc32;
    return true;
  }
  const char* name(size_t index) const override { return index < count() ? Data::ENTRIES[index].name : ""; }
  bool select(uint8_t id) override {
    selected_ = nullptr;
    for (const Data::Entry& e : Data::ENTRIES)
      if (e.id == id) selected_ = &e;
    return selected_ != nullptr;
  }
  uint32_t irCount() const override { return selected_ ? selected_->irCount : 0; }
  uint32_t spo2Count() const override { return selected_ ? selected_->spo2Count : 0; }
  uint32_t imuCount() const override { return selected_ ? selected_->imuCount : 0; }
  bool ir(uint32_t index, float& value) const override {
    if (!selected_ || index >= selected_->irCount) return false;
    value = selected_->ir[index];
    return true;
  }
  bool spo2(uint32_t second, float& value, bool& valid) const override {
    if (!selected_ || second >= selected_->spo2Count) return false;
    valid = selected_->spo2Valid[second] != 0;
    value = selected_->spo2[second];
    return true;
  }
  bool imu(uint32_t index, float* axes) const override {
    if (!selected_ || index >= selected_->imuCount) return false;
    memcpy(axes, selected_->imu + index * 6u, 6 * sizeof(float));
    return true;
  }

 private:
  const Data::Entry* selected_ = nullptr;
};
}  // namespace Scenario
"""]
    HEADER.write_text("".join(parts), encoding="utf-8", newline="\n")
    print(f"Wrote {HEADER} ({HEADER.stat().st_size // 1024} KiB, {len(entries)} scenarios)")


if __name__ == "__main__":
    main()
